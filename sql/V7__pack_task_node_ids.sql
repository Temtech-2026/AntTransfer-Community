-- =====================================================================
-- AntTransfer CE — V7：sys_pack_task 增列 node_ids（打包任务的输入清单）
--
-- 背景：批量打包下载（PRD US-12）是**异步任务**——创建时只入队，真正压 zip 由线程池
-- 在事务提交后执行，产物落临时区、设过期时间，再由定时任务清理。
--
-- 【为什么必须把「要打哪些文件」落库】
--   V6 的 sys_pack_task 只存了 file_count / total_bytes 这类汇总值，缺少输入清单。
--   若把条目 ID 列表只放在工作线程的内存闭包里：
--     · 进程重启、线程池拒绝、任务重试 → 再也说不清「这一单该打哪些文件」，只能留下
--       一条永远停在 status=0 的僵尸行，还一直占着「每用户并发打包数」的名额；
--     · 排障时无法回答「用户提交的这一单到底包含什么」，事后审计也断链。
--   落库后任务自包含：可安全重试，且与 sys_operation_log 里的 taskNo 能对上。
--
-- 【为什么用逗号分隔的 text 而不是明细子表】
--   清单仅用于「重建一次打包」，不参与任何按条目反查（不需要 `where node_id = ?`），
--   建子表只会多一次写放大与一张需要单独清理的表。若后续要支持「按文件查它进过哪些打包单」，
--   再引入 sys_pack_task_item 明细表即可，本列随即可弃用。
--
-- 注意：纯增量（只增列），不改写既有列语义；已执行过 V1~V6 的库可增量执行。
-- =====================================================================

alter table sys_pack_task
    add column node_ids text null comment '待打包条目 ID 列表（英文逗号分隔，顺序即 zip 内条目顺序；异步任务自包含所需）'
    after total_bytes;
