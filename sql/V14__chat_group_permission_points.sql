-- =====================================================================
-- V14__chat_group_permission_points.sql — 会话群聊权限点（建群闭环）
--
-- 背景：聊天弹窗此前只能「手填一个已存在的群组 ID」，而系统从未提供任何创建群组的
--   能力——sys_group / sys_group_member 有表，发送侧也有成员校验与写扩散，
--   唯独没有任何建群 / 查群的接口，导致群聊实际不可用（永远不存在可填的群）。
--   本次补齐建群闭环（POST /v1/chat/groups + GET /v1/chat/groups），故需对应权限点。
--
-- 基线：依赖 V1（sys_permission / sys_role_permission）、V2（内置角色）、
--   V4（sys_group / sys_group_member）、V9（system:* 的 id 安排）。
--   本脚本只增不改：不触碰此前脚本已写入的任何行（Flyway 已执行脚本禁止回改）。
--
-- ---------------------------------------------------------------------
-- 授权口径（本脚本两条红线，回改前请先读这里）
-- ---------------------------------------------------------------------
--   ① 建群是写操作，AUDITOR 一个点都不授予。审计员「权限锁定只读」由三处共同保证：
--      V2 只授 audit:log:read、本脚本不授 chat:group:create、服务层拒绝对 AUDITOR 的
--      权限集做任何变更（1021 AUDITOR_PERM_LOCKED）。数据层与服务层双保险，
--      任一层被绕过仍不越权。
--   ② 查询「我加入的群」（GET /v1/chat/groups）刻意不设权限点：它只返回调用者本人
--      在 sys_group_member 里的那些群，查询维度写死在服务端登录态上，不存在
--      「传别人的 ID 读别人的群」这个入参面——与会话列表 / 单聊目标解析同属
--      「登录即充分」。若给它加权限点，默认角色拿不到就会表现为
--      「建完群却看不到群」，把可用性事故伪装成权限配置问题。
--
-- 固定主键：id 为脚本固定小整数（菜单取 103，接 V2 的 100/101 与 V9 的 102；
--   操作点取 150，接 V9 的 130..144 段），仅用于脚本间逻辑关联；
--   运行期新行由雪花算法分配大整数主键，不冲突。
--
-- PostgreSQL 差异：本文件为 MySQL 8 方言；末段 `insert ... select` 两库通用。
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. 菜单根节点：会话（type=1，parent_id=0）
--    与 file(100) / audit(101) / system(102) 并列，使群聊权限点有挂载点。
-- ---------------------------------------------------------------------
insert into sys_permission (id, perm_code, perm_name, type, parent_id, sort_no)
values (103, 'chat', '会话', 1, 0, 4);

-- ---------------------------------------------------------------------
-- 2. 群聊操作点（type=2，挂 103 之下）
--    只设「建群」一个点：会话的读 / 发 / 已读沿用既有的「登录即充分」口径
--    （见 ChatController 类注），本脚本不为此新增门禁，避免把聊天本身锁死。
-- ---------------------------------------------------------------------
insert into sys_permission (id, perm_code, perm_name, type, parent_id, sort_no)
values (150, 'chat:group:create', '创建群聊', 2, 103, 1);

-- ---------------------------------------------------------------------
-- 3. 授权：三个业务角色（不含 AUDITOR，理由见文件头 ①）
--    按 perm_code / role.code 定位而非硬编码 id，避免与后续脚本的 id 安排强耦合；
--    id 取 1000 + role_id * 100 + permission_id（role 1..4 × perm 103/150），
--    与 V2 已占用的 1..27、V9 的 202..244 均不重叠。
-- ---------------------------------------------------------------------
insert into sys_role_permission (id, role_id, permission_id)
select 1000 + r.id * 100 + p.id, r.id, p.id
from sys_role r
         join sys_permission p
              on p.perm_code = 'chat' or p.perm_code = 'chat:group:create'
where r.code in ('SUPER_ADMIN', 'DEPT_ADMIN', 'USER');
