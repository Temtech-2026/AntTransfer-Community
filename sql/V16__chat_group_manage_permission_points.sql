-- =====================================================================
-- V16__chat_group_manage_permission_points.sql — 群组管理权限点（群配置闭环）
--
-- 背景：V14 打通了「建群」这一环，但群建出来之后在事实上不可维护——群名打错了
--   只能重新建群（历史会话随之作废），人走了还挂在群里、想拉人进来也无处可点，
--   群主也没有解散的出口。本次补齐群管理面：
--     GET    /v1/chat/groups/{groupId}                 群详情（成员名单 + 我的可操作项）
--     PATCH  /v1/chat/groups/{groupId}                 改群名
--     POST   /v1/chat/groups/{groupId}/members         邀请成员
--     DELETE /v1/chat/groups/{groupId}/members/{userId} 移除成员
--     POST   /v1/chat/groups/{groupId}/quit            退出群聊
--     DELETE /v1/chat/groups/{groupId}                 解散群聊
--
-- 基线：依赖 V1（sys_permission / sys_role_permission）、V2（内置角色）、
--   V4（sys_group / sys_group_member）、V14（chat 菜单 103 与 chat:group:create 150）。
--   本脚本只增不改：不触碰此前脚本已写入的任何行（Flyway 已执行脚本禁止回改），
--   也不重复插入 V14 已建的 chat 菜单节点。
--
-- ---------------------------------------------------------------------
-- 授权口径（本脚本三条红线，回改前请先读这里）
-- ---------------------------------------------------------------------
--   ① 建群/管理都是写操作，AUDITOR 一个点都不授予。与 V14 同口径：审计员「权限锁定
--      只读」由 V2（不授写类权限点）、本脚本（不授群管理点）、服务层（1021）三处共同保证，
--      任一层被绕过仍不越权。
--   ② 群详情（GET /v1/chat/groups/{groupId}）与退出群聊（POST .../quit）刻意不设权限点：
--      · 群详情的查询维度是「我与该群的关系」，非成员一律 1012，不存在「传别人的群 ID
--        读别人的群资料」的入参面；
--      · 退出群聊的作用对象写死为登录人自己（路径里没有他人的 ID），越权面为零。
--      若给这两者加权限点，默认角色拿不到就会表现为「建完群却打不开群设置」或
--      「进了群却退不出去」，把可用性事故伪装成权限配置问题。
--   ③ 权限点只表达「这个账号有没有群管理这项功能」；「这个群归不归他管」由服务层的
--      群内身份判定回答（改群名 / 邀请 = 群主或管理员，移除 / 解散 = 仅群主），
--      不足分别返回 1038 / 1041，与权限点不足的 1003 刻意分开——提示与自救动作不同。
--
-- 固定主键：操作点取 151..154，接 V14 的 150；菜单沿用 V14 已建的 chat(103)，
--   本脚本不再插入菜单行。id 仅用于脚本间逻辑关联，运行期新行由雪花算法分配大整数主键。
--
-- PostgreSQL 差异：本文件为 MySQL 8 方言；末段 `insert ... select` 两库通用。
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. 群管理操作点（type=2，挂 V14 已建的 chat(103) 之下）
--    sort_no 续 V14 的「创建群聊(1)」，按「日常可逆 → 破坏不可逆」从轻到重排列：
--    改群名 / 邀请为日常管理，移除 / 解散为破坏性操作，顺序即风险顺序。
-- ---------------------------------------------------------------------
insert into sys_permission (id, perm_code, perm_name, type, parent_id, sort_no)
values (151, 'chat:group:update', '修改群名', 2, 103, 2),
       (152, 'chat:group:invite', '邀请群成员', 2, 103, 3),
       (153, 'chat:group:remove', '移除群成员', 2, 103, 4),
       (154, 'chat:group:dissolve', '解散群聊', 2, 103, 5);

-- ---------------------------------------------------------------------
-- 2. 授权：三个业务角色（不含 AUDITOR，理由见文件头 ①）
--    按 perm_code / role.code 定位而非硬编码 id，避免与后续脚本的 id 安排强耦合；
--    id 取 1000 + role_id * 100 + permission_id，即 1251..1254 / 1351..1354 / 1451..1454，
--    与 V2 已占用的 1..27、V9 的 202..244、V14 的 1203..1450 均不重叠。
--
--    四个点整组授予同一批角色：若只授其中一部分（例如官方角色能改群名但不能邀请），
--    用户会在同一个面板上遇到「有的按钮能点、有的提示无权限」的割裂体验，
--    而这两者的授权粒度并无产品差异——真正的差异化在群内身份，不在角色。
-- ---------------------------------------------------------------------
insert into sys_role_permission (id, role_id, permission_id)
select 1000 + r.id * 100 + p.id, r.id, p.id
from sys_role r
         join sys_permission p
              on p.perm_code in ('chat:group:update', 'chat:group:invite',
                                 'chat:group:remove', 'chat:group:dissolve')
where r.code in ('SUPER_ADMIN', 'DEPT_ADMIN', 'USER');
