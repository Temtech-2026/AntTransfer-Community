-- =====================================================================
-- V18__chat_mention_and_retention.sql — 会话消息「@ 提及」标记 + 保留期清理索引
--
-- 背景：PRD §4 P1「站内轻 IM（会话与 @ 提及）」要求两件事——「@ 提及」与
--   「消息持久化 ≥ 30 天」。此前两者都只有口径、没有落地：
--     · 群聊里 @某人 只是一串人类可读的文本，被 @ 的人与其他成员拿到的是**一模一样**的行，
--       服务端并不知道「这条消息点名了谁」，因此给不出任何定向提示（未读高亮无从谈起）；
--     · 消息表只增不删，「≥ 30 天」既没有下限保障、也没有超期收口。
--   本脚本为前者补一列，为后者补一条索引（保留期本身是策略值，不落列）。
--
-- 基线：依赖 V1（sys_notify_message 建表）、V5（会话列 + idx_session）。
--   本脚本只增不改：不触碰既有列、不改既有索引（Flyway 已执行脚本禁止回改）。
--
-- ---------------------------------------------------------------------
-- 设计口径（回改前请先读这里）
-- ---------------------------------------------------------------------
--   ① mentioned 是「本行接收人是否被本条消息点名」的**行级属性**，不是消息级属性。
--      写扩散下一条消息落 N 行（单聊 2 行、群聊 N 行），其中只有「被 @ 的那个人」
--      的那一行置 1；发送人自己那一行恒为 0（自己 @ 自己无意义）。
--      于是「有没有人 @ 我」退化为 `mentioned = 1 and read_status = 0` 的等值查询——
--      与写扩散「未读 / 已读全部按 recipient 单表查」的既有形态完全同构。
--
--      为什么不解析正文里的 "@昵称"：昵称可重名、可修改、可含空格与特殊字符，
--      以文本反查「被点名的是谁」必然误判；而发送端本来就知道点的是谁（选了哪个人），
--      让它显式带上用户 ID 是唯一可靠的信息源。正文里的 "@昵称" 仍由前端按文本渲染。
--
--      为什么不存「完整提及名单」：那会让**每一行**都冗余一份 N 长度的列表，
--      写放大随群规模平方增长（500 人群一条 @3 人的消息要多写几 KB）；
--      而它唯二的用途——「未读高亮」只需本行的布尔值，「谁被 @ 了」前端发送时自己就知道。
--
--   ② 保留期不落列：保留期是**服务端策略**（配置项，下限 30 天），不是数据事实。
--      清理按 create_time 与「当前时刻 - 保留期」比对，无需任何新列。
--      ⚠️ 与 V15 口径 ④「撤回窗口不落库、不建列」同一取舍：策略值只在代码 / 配置里
--      定义一处，避免「改了配置忘了改注释」这类只在边界时刻才暴露的偏差。
--
--   ③ 清理只作用于**会话消息**（chat_scope 非空），不触碰系统通知：
--      收件箱通知的保留期涉及待办中心与审批留痕（「待办在用户没处理前不能消失」，
--      见 NotifyMessageService 类注），属独立命题，本脚本不为它定义口径。
--      故新索引以 chat_scope 为前导列，把扫描范围直接限定在会话消息这一侧。
--
--   ④ 索引 idx_scope_created 存在的理由：
--      清理 SQL 形如 `where chat_scope > 0 and create_time < ? order by create_time limit N`。
--      没有本索引时，每一批都要全表扫 create_time 再回表过滤 chat_scope——
--      而表里数量级更大的恰恰是永远不满足条件的系统通知（chat_scope 为 NULL），
--      它们会一直挡在扫描路径最前，使「扫了几十万行却删不掉几行」成为每批的常态。
--      以 chat_scope 前导，扫描可直接定位到会话消息这一段。
--      ⚠️ 谓词写 `chat_scope > 0` 而非 `chat_scope is not null`：两者语义等价
--      （ChatScope 取值恒为正），但前者在 MySQL 上是明确的 range 条件，索引选择更稳定。
--
-- PostgreSQL 差异：本文件为 MySQL 8 方言；`add column ... after` 与 `comment` 为 MySQL 专有，
--   EE 若需 PG 版本请另写 V18 的 PG 变体（`COMMENT ON COLUMN` + 无 `after` 子句）。
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. @ 提及标记列
--    mentioned：0-本行接收人未被点名 1-本行接收人被点名
--    默认 0，历史行自动成为「未被点名」——与事实相符（此前不存在提及概念）。
--    tinyint 而非 boolean：与 read_status / recall_status 的既有列风格一致，
--    且避免 MySQL 的 tinyint(1) / PG 的 boolean 在两侧类型名不统一。
-- ---------------------------------------------------------------------
alter table sys_notify_message
    add column mentioned tinyint not null default 0
        comment '@ 提及：0-未点名 1-本行接收人被本条消息点名（行级属性，见 V18 口径 ①）'
        after read_status;

-- ---------------------------------------------------------------------
-- 2. 保留期清理扫描索引
--    支撑 `where chat_scope > 0 and create_time < ? order by create_time limit N`
--    （见 V18 口径 ④）。
--    不建 (mentioned, read_status) 相关索引：会话列表的「提及未读」计数
--    与未读计数在同一行上取列计算，复用 idx_session 的分组顺序即可，
--    额外索引只会给这张写扩散热表增加一份写开销而换不到读收益。
-- ---------------------------------------------------------------------
create index idx_scope_created on sys_notify_message (chat_scope, create_time);
