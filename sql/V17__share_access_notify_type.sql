-- V17__share_access_notify_type.sql
-- 外发链接「取件回执」的通知类型落库（notify_type 注释口径扩至 9）
-- ---------------------------------------------------------------------
-- 背景：US-08 的通知类型白名单在 V5 收敛到 8（传输完成提醒）。外发链接主线此前只有
--   3 / 4 两个**负向**提醒（链接被锁 / 即将到期），而「有人真的取走了文件」这条
--   **正向事实**没有任何通知出口——创建者只能自己去翻取件审计，是协作链路上的信息断点。
--   at-file 取件链路（ShareAccessService#redeem）落地该回执后，需要 9 这个编码。
--
-- 设计口径：
--   1) 9 与 8 同段（业务提醒），命名 SHARE_ACCESSED，与 3 / 4 **并列而不复用**：
--      复用 3 会把「取件成功」在收件箱显示成「链接被锁定」，是比不发更糟的语义误导
--      （与「授权到期回收」不映射到「审批结果」2 的既有裁定同一口径）；
--   2) **计入站内信未读**：未读 SQL 为 `notify_type not in (6,7)`，9 自动纳入，无需改 Mapper；
--   3) **不进待办中心**：待办 SQL 为 `notify_type in (1,2,8)`，9 不参与 /v1/todos 投影
--      ——「有人取件」是告知而非待处置事项，放进待办只会制造没有动作可做的僵尸待办；
--   4) **不做跨次幂等**：每次成功取件各发一条（「又一次取件」本身即新事实），
--      因此 bizType + bizId + notifyType 三元幂等键在本类型上**不可**用于去重；
--      通知量由链接自身的 download_limit 额度闸门约束（见 sys_share_link）。
--
-- ⚠️ 与 V1 / V5 的关系：两者均为已发布脚本，按 sql/README.md
--   「已执行脚本禁止修改（Flyway checksum 铁律）」**不回改**；
--   本脚本沿用 V5 的做法，仅 MODIFY COLUMN 更新注释，使 DB 内注释与
--   at-common NotifyType 编码表保持一致（注释即该字段的权威口径说明）。
--
-- 结构影响：无（列类型 / 可空性 / 默认值 / 列序均与 V5 后状态逐字一致，仅注释追加 9）。
-- 数据影响：无（不改任何行；只在 DDL 层同步注释）。
--
-- PostgreSQL 差异：本文件为 MySQL 8 方言。`MODIFY COLUMN` 为 MySQL 专有，
--   PG 需改为 `COMMENT ON COLUMN sys_notify_message.notify_type IS '...'`。
-- =====================================================================

-- ---------------------------------------------------------------------
-- notify_type 注释口径更新：纳入 9（新增 9 = 外发链接被取件回执）
--   1~5 系统通知（US-08 白名单，计入导航栏红点）；
--   6~7 会话消息（计入会话角标，**不计入**导航栏纯提醒红点）；
--   8   传输完成提醒；
--   9   外发链接取件回执（计入红点，不进待办）。
-- ---------------------------------------------------------------------
alter table sys_notify_message
    modify column notify_type tinyint not null comment '通知类型：1-审批待办 2-审批结果 3-外发链接锁定 4-链接到期提醒 5-异常登录告警 6-单聊消息 7-群聊消息 8-传输完成提醒 9-外发链接取件回执（编码表见 at-common NotifyType）';
