/**
 * 内置表情表。
 *
 * <p><b>为什么是内置字符而不是表情图片 / 第三方组件：</b></p>
 * <ol>
 *   <li><b>聊天正文是纯文本。</b>后端 {@code ChatSendDTO.content} 落在
 *       {@code sys_notify_message.content}（`varchar(1000)`，表字符集 utf8mb4），
 *       存的就是 Unicode 字符本身。用图片贴纸得另立一套编码与存储协议，
 *       还会让历史消息在别处渲染时变成乱码。</li>
 *   <li><b>零依赖、零网络。</b>表情面板只用到系统字体，离线可用，
 *       也不受第三方 CDN / 包体体积影响。</li>
 *   <li><b>长度口径一致。</b>前端 `maxLength` 与后端 {@code @Size(max = 1000)}
 *       都按 UTF-16 码元计数，表情与中文混排时的计数完全一致；
 *       换成图片方案就得另定一套长度规则。</li>
 * </ol>
 *
 * <p>分组只做「找起来快」的粗分，不追求 emoji 官方分类的完备性——
 * 全部约 200 个，覆盖日常协作沟通够用。</p>
 */

